/** Search countries by name or code */
export function searchCountries(query: string): Country[] {
  if (!query || query.length < 1) return COUNTRIES;
  const q = query.toLowerCase();
  return COUNTRIES.filter(
    (c) => c.name.toLowerCase().includes(q) || c.code.toLowerCase() === q || c.dialCode.includes(q)
  );
}

/** Get country by ISO code */
export function getCountryByCode(code: string): Country | undefined {
  return COUNTRIES.find((c) => c.code === code.toUpperCase());
}

/** Get default currency for a country */
export function getCurrencyForCountry(code: string): string {
  return getCountryByCode(code)?.currency ?? "USD";
}

/** Get dial code for a country */
export function getDialCodeForCountry(code: string): string {
  return getCountryByCode(code)?.dialCode ?? "+1";
}
