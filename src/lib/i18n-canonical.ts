// ── Merge all domains ────────────────────────────────────────────────────────
function mergeAll(...sources: Record<AppLocale, Record<string, string>>[]): Record<AppLocale, Record<string, string>> {
  const result: Record<AppLocale, Record<string, string>> = { en: {}, fr: {}, ar: {} };
  for (const source of sources) {
    for (const locale of ["en", "fr", "ar"] as AppLocale[]) {
      Object.assign(result[locale], source[locale]);
    }
  }
  return result;
}

const ALL_TRANSLATIONS = mergeAll(nav, orbit, commerce, wallet, settings, common, auth);

// ── Locale detection ─────────────────────────────────────────────────────────
let _locale: AppLocale | null = null;

export function getAppLocale(): AppLocale {
  if (_locale) return _locale;
  try {
    const stored = localStorage.getItem("app-locale");
    if (stored === "fr" || stored === "ar") { _locale = stored; return stored; }
    const lang = navigator.language?.split("-")[0];
    if (lang === "fr" || lang === "ar") { _locale = lang as AppLocale; return _locale; }
  } catch {}
  _locale = "en";
  return "en";
}

export function setAppLocale(locale: AppLocale): void {
  _locale = locale;
  try { localStorage.setItem("app-locale", locale); } catch {}
}

export function resetAppLocale(): void { _locale = null; }

export function isRTL(): boolean { return getAppLocale() === "ar"; }

// ── Core translate function ──────────────────────────────────────────────────
/**
 * Canonical translate: tc("commerce.add_to_cart") or tc("common.km_away", { distance: "2.3" })
 */
export function tc(key: string, params?: Record<string, string | number>): string {
  const locale = getAppLocale();
  let value = ALL_TRANSLATIONS[locale]?.[key] || ALL_TRANSLATIONS.en[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      value = value.replace(`{${k}}`, String(v));
    }
  }
  return value;
}

/** Check if a key exists */
export function hasKey(key: string): boolean {
  return key in ALL_TRANSLATIONS.en;
}

/** Get all keys for a domain prefix */
export function getDomainKeys(prefix: string): Record<string, string> {
  const locale = getAppLocale();
  const dict = ALL_TRANSLATIONS[locale] || ALL_TRANSLATIONS.en;
  const result: Record<string, string> = {};
  for (const [k, v] of Object.entries(dict)) {
    if (k.startsWith(prefix)) result[k] = v;
  }
  return result;
}
