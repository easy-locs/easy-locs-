function getLabels(country: string): Record<string, string> {
  const langMap: Record<string, string> = {
    FR: "fr", BE: "fr", CH: "fr", MA: "fr", TN: "fr", DZ: "fr", LU: "fr",
    ES: "es", MX: "es", AR: "es", CL: "es", CO: "es",
    DE: "de", AT: "de",
    IT: "it",
    PT: "pt", BR: "pt",
    AE: "ar", SA: "ar", QA: "ar", EG: "ar",
  };
  return INVOICE_LABELS[langMap[country] || "en"] || INVOICE_LABELS.en;
}

function formatDate(date: Date, country: string): string {
  const locale = COUNTRY_LOCALE[country] || "en-GB";
  try {
    return new Intl.DateTimeFormat(locale, { day: "2-digit", month: "long", year: "numeric" }).format(date);
  } catch { return date.toLocaleDateString("en-GB"); }
}

function formatAmount(amount: number, currency: string, country: string): string {
  const locale = COUNTRY_LOCALE[country] || "en-US";
  try {
    return new Intl.NumberFormat(locale, { style: "currency", currency, minimumFractionDigits: 2 }).format(amount);
  } catch { return `${amount.toFixed(2)} ${currency}`; }
}

function loadLogoAsBase64(url: string): Promise<string | null> {
  return new Promise((resolve) => {
    if (!url) return resolve(null);
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.onload = () => {
      const canvas = document.createElement("canvas");
      canvas.width = img.width;
      canvas.height = img.height;
      canvas.getContext("2d")?.drawImage(img, 0, 0);
      try { resolve(canvas.toDataURL("image/png")); } catch { resolve(null); }
    };
    img.onerror = () => resolve(null);
    img.src = url;
  });
}

