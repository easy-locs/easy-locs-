export function getStoriesForFeed(feedKey: string): Story[] {
  const domainMap: Record<string, (s: Story) => boolean> = {
    dashboard_for_you: () => true,
    dashboard_trending: (s) => (s.rankingSignals.popularity ?? 0) > 80,
    radar_nearby: () => true,
    property_buy: (s) => s.vertical === "property" && s.subcategoryKey.startsWith("buy"),
    property_rent: (s) => s.vertical === "property" && s.subcategoryKey.startsWith("rent"),
    property_projects: (s) => s.vertical === "property" && (s.subcategoryKey.includes("offplan") || s.subcategoryKey.includes("project") || s.subcategoryKey === "investment"),
    stay_trending: (s) => s.vertical === "stay" || (s.storyType === "deal" && s.vertical === "stay"),
    food_nearby: (s) => s.vertical === "food" || (s.storyType === "deal" && s.vertical === "food"),
    grocery_nearby: (s) => s.vertical === "grocery",
    shops_trending: (s) => s.vertical === "shops",
    shops_fashion: (s) => s.vertical === "shops" && s.subcategoryKey === "fashion",
    shops_electronics: (s) => s.vertical === "shops" && s.subcategoryKey === "electronics",
    services_nearby: (s) => s.vertical === "services",
    services_repair: (s) => s.vertical === "services" && ["plumbing", "electrical", "ac_repair", "handyman", "car_repair"].includes(s.subcategoryKey),
    services_beauty: (s) => s.vertical === "services" && ["salon", "barber", "spa", "beauty"].includes(s.subcategoryKey),
  };

  const filter = domainMap[feedKey];
  if (!filter) return filterValidStories(FALLBACK_STORIES, feedKey);

  const stories = FALLBACK_STORIES.filter(s => s.isActive && filter(s));
  const validated = filterValidStories(stories, feedKey);

  return validated.sort((a, b) => {
    const scoreA = (a.rankingSignals.quality ?? 0) * 0.4 + (a.rankingSignals.freshness ?? 0) * 0.3 + (a.rankingSignals.popularity ?? 0) * 0.3;
    const scoreB = (b.rankingSignals.quality ?? 0) * 0.4 + (b.rankingSignals.freshness ?? 0) * 0.3 + (b.rankingSignals.popularity ?? 0) * 0.3;
    return scoreB - scoreA;
  });
}
