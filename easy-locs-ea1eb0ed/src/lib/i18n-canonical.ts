// ── Merge all domains ────────────────────────────────────────────────────────
function mergeAll(...sources: Partial<Record<AppLocale, Record<string, string>>>[]): Record<AppLocale, Record<string, string>> {
  const result = {} as Record<AppLocale, Record<string, string>>;
  for (const locale of APP_LOCALES) {
    result[locale] = {};
  }
  for (const source of sources) {
    for (const locale of APP_LOCALES) {
      if (source[locale]) {
        Object.assign(result[locale], source[locale]);
      }
    }
  }
  return result;
}

const ALL_TRANSLATIONS = mergeAll(nav, orbit, commerce, wallet, settings, common, commonExtended, auth, mobility, radar, propertyDomain, realEstateVertical, travel, c2c, chatPayments, deliveryChat, mapSearch, mfa, propertiesShowcase, admin);

// ── Locale detection ─────────────────────────────────────────────────────────
const _appLocaleSet: ReadonlySet<string> = new Set<string>(APP_LOCALES);
let _locale: AppLocale | null = null;

export function getAppLocale(): AppLocale {
  if (_locale) return _locale;
  try {
    const stored = localStorage.getItem("app-locale");
    if (stored && _appLocaleSet.has(stored)) { _locale = stored as AppLocale; return _locale; }
    const lang = navigator.language?.split("-")[0];
    if (lang && _appLocaleSet.has(lang)) { _locale = lang as AppLocale; return _locale; }
  } catch {}
  _locale = "en";
  return "en";
}

export function setAppLocale(locale: AppLocale): void {
  _locale = locale;
  try { localStorage.setItem("app-locale", locale); } catch {}
  try {
    document.documentElement.dir = RTL_LOCALES.has(locale) ? "rtl" : "ltr";
    document.documentElement.lang = locale;
  } catch {}
}

export function resetAppLocale(): void { _locale = null; }

export function isRTL(): boolean { return RTL_LOCALES.has(getAppLocale()); }

export function getDirection(): "ltr" | "rtl" { return isRTL() ? "rtl" : "ltr"; }

// ── Core translate function ──────────────────────────────────────────────────
import { humanizeKey, looksLikeI18nKey } from "@/lib/i18n-safe";

const _missingCanonical = new Set<string>();

/**
 * Canonical translate: tc("commerce.add_to_cart") or tc("common.km_away", { distance: "2.3" })
 * NEVER returns a raw key — humanizes as last resort.
 */
export function tc(key: string, params?: Record<string, string | number>): string {
  const locale = getAppLocale();
  const raw = ALL_TRANSLATIONS[locale]?.[key] || ALL_TRANSLATIONS.en[key];
  let value: string;
  if (raw) {
    value = raw;
  } else {
    // Key missing — humanize, never show raw key
    if (import.meta.env.DEV && !_missingCanonical.has(key)) {
      _missingCanonical.add(key);
      console.warn(`[tc-missing] "${key}"`);
    }
    value = humanizeKey(key);
  }
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      value = value.replace(`{${k}}`, String(v));
    }
  }
  return value;
}

/**
 * Plural-aware canonical translate.
 * Resolves `key_one` / `key_other` based on count, then interpolates params.
 */
export function tcp(key: string, count: number, params?: Record<string, string | number>): string {
  const suffix = count === 1 ? "_one" : "_other";
  const resolvedKey = hasKey(key + suffix) ? key + suffix : key;
  return tc(resolvedKey, { count, ...params });
}

/** Check if a key exists */
export function hasKey(key: string): boolean {
  return key in ALL_TRANSLATIONS.en;
}

/** Get all keys for a domain prefix */
export function getDomainKeys(prefix: string): Record<string, string> {
  const locale = getAppLocale();
  const dict = ALL_TRANSLATIONS[locale] || ALL_TRANSLATIONS.en;
  const result: Record<string, string> = {};
  for (const [k, v] of Object.entries(dict)) {
    if (k.startsWith(prefix)) result[k] = v;
  }
  return result;
}
