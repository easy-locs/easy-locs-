export function resolveTimezoneForCity(cityName: string): string | null {
  const entry = TIMEZONE_MAP.find(
    (e) => e.city.toLowerCase() === cityName.toLowerCase()
  );
  return entry?.timezone ?? null;
}

export function getCitiesForTimezone(tz: string): TimezoneEntry[] {
  return TIMEZONE_MAP.filter((e) => e.timezone === tz);
}

export function getCitiesForCountry(countryCode: string): TimezoneEntry[] {
  return TIMEZONE_MAP.filter((e) => e.country === countryCode.toUpperCase());
}

export function findNearestCity(lat: number, lng: number): TimezoneEntry | null {
  if (TIMEZONE_MAP.length === 0) return null;
  let nearest = TIMEZONE_MAP[0];
  let minDist = Infinity;
  for (const entry of TIMEZONE_MAP) {
    const d = Math.sqrt((entry.lat - lat) ** 2 + (entry.lng - lng) ** 2);
    if (d < minDist) { minDist = d; nearest = entry; }
  }
  return nearest;
}
