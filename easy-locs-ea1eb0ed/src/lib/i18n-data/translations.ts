export function getMissingTranslationKeys(locale: string, referenceLocale = "en"): string[] {
  const ref = GLOBAL_TRANSLATIONS[referenceLocale];
  const target = GLOBAL_TRANSLATIONS[locale];
  if (!ref || !target) return [];
  return Object.keys(ref).filter((key) => !(key in target));
}

export function getTranslationCoverage(): Record<string, { total: number; translated: number; percent: number }> {
  const refKeys = Object.keys(GLOBAL_TRANSLATIONS["en"] || {});
  const total = refKeys.length;
  const coverage: Record<string, { total: number; translated: number; percent: number }> = {};
  for (const [locale, dict] of Object.entries(GLOBAL_TRANSLATIONS)) {
    const translated = refKeys.filter((k) => k in dict).length;
    coverage[locale] = { total, translated, percent: Math.round((translated / total) * 100) };
  }
  return coverage;
}
